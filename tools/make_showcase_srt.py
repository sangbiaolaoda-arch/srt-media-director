"""生成 showcase 样例库的 SRT 与说明文件。

本项目最大的卖点是「反 PPT / 画面会讲故事」，但过去只有自己写的情绪独白
一段。外人无法验证。因此内置一组**覆盖不同内容类型**的样例字幕，并刻意
保留失败案例，让能力边界可被检验，而不是只展示最好的一段。

输出：
    examples/showcase/01-explanatory-tech/case.srt   技术讲解（因果链/流程）
    examples/showcase/02-narrative-emotion/case.srt  叙事抒情（问答/让步）
    examples/showcase/03-data-comparison/case.srt    数据对比（数字/前后）
    examples/showcase/04-longform-3min/case.srt      长片 ≥3 分钟

SRT 时间轴由本脚本按每句字数自动推算，保证格式合法、无重叠、总时长可控。
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "examples", "showcase")


def _fmt(t):
    h = int(t // 3600)
    m = int((t % 3600) // 60)
    s = int(t % 60)
    ms = int(round((t - int(t)) * 1000))
    return "%02d:%02d:%02d,%03d" % (h, m, s, ms)


def build_srt(lines, cps=5.2, gap=0.12, min_dur=0.9):
    """按字符数推算每条时长，返回 SRT 文本。cps=每秒钟读约 5.2 字。"""
    out, t = [], 0.0
    for i, text in enumerate(lines, 1):
        dur = max(min_dur, len(text) / cps)
        start, end = t, t + dur
        out.append("%d\n%s --> %s\n%s\n\n" % (i, _fmt(start), _fmt(end), text))
        t = end + gap
    return "".join(out), t


