def main():
    for slug, title, lines in CASES:
        d = os.path.join(OUT, slug)
        os.makedirs(d, exist_ok=True)
        text, total = build_srt(lines, cps=5.2, gap=0.12)
        with open(os.path.join(d, "case.srt"), "w", encoding="utf-8") as f:
            f.write(text)
        with open(os.path.join(d, "notes.md"), "w", encoding="utf-8") as f:
            f.write("# %s\n\n" % title)
            f.write("- 行数（cues）：%d\n" % len(lines))
