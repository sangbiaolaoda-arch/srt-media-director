"""gsap_emit.py — compile the capability catalogs into browser-ready artifacts.

Additive. Emits, next to the output dir:

  capability-layouts.json    — all layout blueprints (JSON)
  capability-entrances.json  — all entrance specs (JSON)
  capability-relations.json  — all relation specs (JSON)
  capability-library.gsap.js — a self-contained UMD bundle exposing
                               ``CapabilityLibrary`` with helpers:
                                 .layouts .entrances .relations
                                 .applyEntrance(el, id)
                                 .runRelation(id, {source, target, link})
                                 .applyLayout(id, slotEls)

The JS *does not* hard-require GSAP; it uses ``window.gsap`` if present and
degrades to a Web Animations / CSS-transition fallback otherwise, so it can be
previewed in any browser. Run:

    python -m capability_library.gsap_emit --out runtime/capability_library/dist
"""
from __future__ import annotations

import argparse
import json
import os

from . import entrance_library, layout_library, relation_library

_JS_HEADER = """/* capability-library.gsap.js — GENERATED by gsap_emit.py. Do not edit.
 * Layouts: %(n_layouts)d  Entrances: %(n_entrances)d  Relations: %(n_relations)d
 * Additive capability bundle for SRT Media Director.
 * Uses window.gsap when available; falls back to WAAPI/CSS.
 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.CapabilityLibrary = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';
  var DATA = %(data)s;
  var _g = (typeof window !== 'undefined' && window.gsap) ? window.gsap : null;

  function _apply(el, props, dur, ease, delay, stagger) {
    if (!el) return;
    var list = (el.length !== undefined && el.nodeType === undefined) ? el : [el];
    if (_g) {
      _g.fromTo(list, props.from, Object.assign({ duration: dur, ease: ease,
        delay: delay || 0, stagger: stagger || 0 }, props.to));
      return;
    }
    // Fallback: WAAPI for opacity/transform-ish props only.
    list.forEach(function (node, i) {
      var css = {};
      ['opacity','filter','clipPath','transform'].forEach(function (k) {
        if (props.from[k] !== undefined) css[k] = props.from[k];
      });
      node.animate([css, {}], { duration: (dur || 0.5) * 1000,
        delay: ((delay || 0) + i * (stagger || 0)) * 1000,
        easing: 'ease-out', fill: 'both' });
    });
  }

  function _byId(arr, id) { for (var i = 0; i < arr.length; i++) if (arr[i].id === id) return arr[i]; return null; }

  return {
    version: '1.0.0',
    layouts: DATA.layouts,
    entrances: DATA.entrances,
    relations: DATA.relations,
    getLayout: function (id) { return _byId(DATA.layouts, id); },
    getEntrance: function (id) { return _byId(DATA.entrances, id); },
    getRelation: function (id) { return _byId(DATA.relations, id); },
    /** Apply an entrance spec to one element or an array of elements. */
    applyEntrance: function (el, id, opts) {
      var e = _byId(DATA.entrances, id); if (!e) return null;
      opts = opts || {};
      _apply(el, { from: e.from, to: e.to },
        opts.duration || e.duration, opts.ease || e.ease,
        opts.delay || 0, opts.stagger !== undefined ? opts.stagger : e.stagger);
      return e;
    },
    /** Run a relation between two elements: {source, target, link, group}. */
    runRelation: function (id, refs) {
      var r = _byId(DATA.relations, id); if (!r) return null;
      refs = refs || {};
      var tl = _g ? _g.timeline() : null;
      r.steps.forEach(function (st) {
        var node = refs[st.target] || refs.source;
        if (st.op === 'tween') _apply(node, { from: {}, to: st.props || {} },
          st.dur || 0.5, st.ease || 'power2.out', 0, 0);
        else if (st.op === 'follow') {
          var off = (refs.source && refs.source.getBoundingClientRect)
            ? refs.source.getBoundingClientRect() : { left: 0, top: 0 };
          _apply(node, { from: {}, to: { x: off.left, y: off.top } },
            0.6, st.ease || 'power2.out', st.delay || 0, 0);
        } else if (st.op === 'chain' && refs.group) {
          _apply(refs.group, { from: { opacity: 0 }, to: { opacity: 1 } },
            0.5, 'power2.out', 0, st.gap || 0.08);
        } else if (st.op === 'sync' && refs.group) {
          _apply(refs.group, { from: {}, to: { scale: 1.05 } }, 0.4, 'power2.inOut', 0, 0);
        }
      });
      return { relation: r, timeline: tl };
    },
    /** Apply a layout by mapping slot -> element. */
    applyLayout: function (id, slotEls, box) {
      var l = _byId(DATA.layouts, id); if (!l) return null;
      box = box || { w: 1280, h: 720 };
      Object.keys(l.regions).forEach(function (slot) {
        var el = slotEls[slot]; if (!el) return;
        var r = l.regions[slot];
        el.style.position = 'absolute';
        el.style.left = (r[0] * box.w) + 'px';
        el.style.top = (r[1] * box.h) + 'px';
        el.style.width = (r[2] * box.w) + 'px';
        el.style.height = (r[3] * box.h) + 'px';
      });
      return l;
    }
  };
});
"""


def emit(out_dir: str) -> dict:
    os.makedirs(out_dir, exist_ok=True)
    layouts = layout_library.all_layouts()
    entrances = entrance_library.all_entrances()
    relations = relation_library.all_relations()

    payloads = {
        "capability-layouts.json": layouts,
        "capability-entrances.json": entrances,
        "capability-relations.json": relations,
    }
    for name, data in payloads.items():
        with open(os.path.join(out_dir, name), "w", encoding="utf-8") as fh:
            json.dump(data, fh, ensure_ascii=False, indent=2)

    data = {"layouts": layouts, "entrances": entrances, "relations": relations}
    js = _JS_HEADER % {
        "n_layouts": len(layouts), "n_entrances": len(entrances),
        "n_relations": len(relations),
        "data": json.dumps(data, ensure_ascii=False),
    }
    js_path = os.path.join(out_dir, "capability-library.gsap.js")
    with open(js_path, "w", encoding="utf-8") as fh:
        fh.write(js)

    return {
        "out_dir": out_dir,
        "layouts": len(layouts),
        "entrances": len(entrances),
        "relations": len(relations),
        "files": list(payloads.keys()) + ["capability-library.gsap.js"],
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Emit capability catalogs to JSON + GSAP bundle")
    ap.add_argument("--out", default="runtime/capability_library/dist")
    args = ap.parse_args(argv)
    info = emit(args.out)
    print(json.dumps(info, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
